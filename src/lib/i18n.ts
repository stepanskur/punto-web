export function useTranslation() {
  const getLang = () => {
    if (typeof window !== 'undefined') {
      return localStorage.getItem('punto_lang') || 'EN';
    }
    return 'EN';
  };
  
  const lang = getLang();
  
  const t = (key: string) => {
    return translations[lang]?.[key] || key;
  };

  return { t, lang };
}
